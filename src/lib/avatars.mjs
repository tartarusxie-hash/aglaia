export function avatarById(id) {
  return AVATARS.find((a) => a.id === id) || null;
}

/** 从头像 URL 反查预设 id（自定义头像 data URL 与未知地址返回 null）。 */
export function presetIdFromUrl(url) {
  if (!url || typeof url !== "string") return null;
  const m = url.match(/\/brand\/avatars\/([a-z0-9-]+)\.webp$/);
  if (!m) return null;
  return AVATARS.some((a) => a.id === m[1]) ? m[1] : null;
}
